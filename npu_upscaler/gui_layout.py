"""Compact guided Windows UI layout: input → setup → 60s preview/full export."""
from PySide6.QtWidgets import (
    QCheckBox, QFormLayout, QGroupBox, QHBoxLayout, QLabel,
    QLineEdit, QProgressBar, QPushButton, QToolButton, QVBoxLayout, QWidget,
)


def build_ui(w, prepared_model=None):
    w.setMinimumWidth(520)
    w.setMaximumWidth(840)
    w.resize(670, 620)
    wrapper = QWidget()
    root = QVBoxLayout(wrapper)
    root.setSpacing(8)
    w.setCentralWidget(wrapper)
    intro = QLabel(
        "① 動画を選ぶ → ② 初回準備 → ③ 先頭60秒で試す → 問題なければ全編変換"
    )
    intro.setWordWrap(True)
    root.addWidget(intro)

    group1 = QGroupBox("① 動画を選ぶ")
    fields = QFormLayout(group1)
    w.source = w._picker(fields, "入力動画", "動画ファイル (*.mp4 *.mkv)", False)
    w.source.setPlaceholderText("MP4 / MKVをここにドラッグ＆ドロップ")
    w.destination = w._picker(fields, "保存先（MP4）", "MP4 (*.mp4)", True)
    root.addWidget(group1)
    w._suggested_output = None

    group2 = QGroupBox("② 初回準備")
    prep = QVBoxLayout(group2)
    w.media_state = QLabel()
    w.media_state.setWordWrap(True)
    prep.addWidget(w.media_state)
    w.media_setup_btn = QPushButton("FFmpegをダウンロード")
    prep.addWidget(w.media_setup_btn)
    w.model_state = QLabel()
    w.model_state.setWordWrap(True)
    prep.addWidget(w.model_state)
    w.model_download_btn = QPushButton("AIモデルをダウンロード")
    prep.addWidget(w.model_download_btn)
    explanation = QLabel("※ FFmpegは動画の読み書き、AIモデルは高画質化に必要です。")
    explanation.setWordWrap(True)
    prep.addWidget(explanation)
    root.addWidget(group2)

    group3 = QGroupBox("③ 変換する")
    actions = QVBoxLayout(group3)
    w.preview = QCheckBox("先頭60秒だけ変換して画質を確認（おすすめ）")
    actions.addWidget(w.preview)
    buttons = QHBoxLayout()
    w.start_btn = QPushButton("NPUで変換を開始")
    w.cancel_btn = QPushButton("キャンセル")
    w.cancel_btn.setEnabled(False)
    buttons.addWidget(w.start_btn, 1)
    buttons.addWidget(w.cancel_btn)
    actions.addLayout(buttons)
    w.guidance = QLabel()
    w.guidance.setWordWrap(True)
    actions.addWidget(w.guidance)
    w.bar = QProgressBar()
    w.bar.setRange(0, 1)
    w.bar.setValue(0)
    actions.addWidget(w.bar)
    w.status = QLabel("準備ができたら変換を開始できます。")
    w.status.setMinimumWidth(0)
    w.status.setWordWrap(True)
    actions.addWidget(w.status)
    root.addWidget(group3)

    w.advanced_btn = QToolButton()
    w.advanced_btn.setText("詳細設定・手動モデル指定")
    w.advanced_btn.setCheckable(True)
    root.addWidget(w.advanced_btn)
    w.advanced_area = QWidget()
    advanced = QVBoxLayout(w.advanced_area)
    model_form = QFormLayout()
    w.model = w._picker(model_form, "モデルXML", "OpenVINO IR (*.xml)", False)
    advanced.addLayout(model_form)
    w.model_setup_btn = QPushButton("モデルZIPをインストール")
    advanced.addWidget(w.model_setup_btn)
    w.driver_help_btn = QPushButton("Intel NPUドライバーの案内")
    advanced.addWidget(w.driver_help_btn)
    w.advanced_area.setVisible(False)
    w.advanced_btn.toggled.connect(w.advanced_area.setVisible)
    root.addWidget(w.advanced_area)

    updates = QHBoxLayout()
    w.update_btn = QPushButton("更新を確認")
    w.auto_update = QCheckBox("起動時に更新を確認")
    w.auto_update.setChecked(w.settings.value("autoCheckUpdates", True, type=bool))
    w.auto_update.toggled.connect(
        lambda checked: w.settings.setValue("autoCheckUpdates", checked)
    )
    updates.addWidget(w.update_btn)
    updates.addWidget(w.auto_update)
    root.addLayout(updates)

    if prepared_model:
        w.model.setText(str(prepared_model))
    w.preview.toggled.connect(w._suggest_output)
    w.preview.setChecked(True)
    w.source.textChanged.connect(w._suggest_output)
    w.source.textChanged.connect(w._refresh_guidance)
    w.model.textChanged.connect(w._refresh_guidance)
    w._refresh_guidance()
